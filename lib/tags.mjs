const KEYWORD_TAGS = [
  { tag: '세금', re: /세법|과세|조세|관세/ },
  { tag: '부동산', re: /주택|부동산|정비법/ },
  { tag: '고시', re: /고시/ },
  { tag: '특정사업', re: /[가-힣0-9]+사업\s*(추진|지원)/ },
];

/** 법제처 법령·행정규칙의 소관부처명 → 도메인 태그. COMMITTEE_TAGS와 같은
 *  원칙(2026-08-14, 오너 지시 — "대통령령이 부동산 관련이면 거기 게시글로
 *  추가해야지, 대통령령이라는 카테고리를 만들란 게 아니다") — 법령 자체가
 *  아니라 그 **내용이 속한 분야**로 분류한다. 부처 소관 사무가 실제로 그
 *  분야인 것만 넣는다, 애매한 부처는 뺀다(국방부 등은 대응하는 국회
 *  위원회 태그가 없는 것과 같은 이유로 뺐다).
 */
export const MINISTRY_TAGS = {
  국토교통부: ['부동산'],
  기획재정부: ['세금'],
  재정경제부: ['세금'], // 기획재정부의 옛 이름(2008년 조직개편 전) — 법령 연혁엔 옛 이름 그대로 남아 있다
  재정경제원: ['세금'], // 재정경제부의 옛 이름(1998년 이전)
  국세청: ['세금'],
  관세청: ['세금'],
  환경부: ['환경'],
  농림축산식품부: ['농업'],
  해양수산부: ['농업'],
  문화체육관광부: ['문화'],
  보건복지부: ['보건'],
  산업통상자원부: ['산업'],
  중소벤처기업부: ['산업'],
  외교부: ['외교'],
  금융위원회: ['금융'],
  행정안전부: ['행정'],
};

function keywordTags(title) {
  const tags = new Set();
  for (const { tag, re } of KEYWORD_TAGS) {
    if (re.test(title)) tags.add(tag);
  }
  return tags;
}

/** 의안 하나(committee·title)에서 확실한 도메인 태그만 뽑는다. 순수 함수. */
export function tagBill(bill) {
  const tags = new Set([...(COMMITTEE_TAGS[bill.committee] || []), ...keywordTags(bill.title)]);
  return [...tags];
}

/** 법령·행정규칙 하나(org·title)에서 확실한 도메인 태그만 뽑는다. 순수 함수.
 *  org는 법제처 응답의 소관부처명 그대로("국방부,방위사업청"처럼 콤마로
 *  여러 부처가 올 수 있다). */
export function tagDecree({ org, title }) {
  const tags = new Set(keywordTags(title));
  for (const ministry of (org || '').split(',').map((s) => s.trim())) {
    for (const t of MINISTRY_TAGS[ministry] || []) tags.add(t);
  }
  return [...tags];
}
