// 실제 bills/*.json 에 나타난 11개 소관위원회 전부를 매핑한다(2026-08-14,
// 69건 실물 데이터 기준). 위원회 소관 사무 그대로다 — 추측이 아니다.
export const COMMITTEE_TAGS = {
  재정경제기획위원회: ['세금'],
  국토교통위원회: ['부동산'],
  법제사법위원회: ['법'],
  기후에너지환경노동위원회: ['환경'],
  농림축산식품해양수산위원회: ['농업'],
  문화체육관광위원회: ['문화'],
  보건복지위원회: ['보건'],
  산업통상자원중소벤처기업위원회: ['산업'],
  외교통일위원회: ['외교'],
  정무위원회: ['금융'],
  행정안전위원회: ['행정'],
};

const KEYWORD_TAGS = [
  { tag: '세금', re: /세법|과세|조세|관세/ },
  { tag: '부동산', re: /주택|부동산|정비법/ },
  { tag: '건축', re: /건축|건설|리모델링|녹색건축|다중생활시설/ },
  { tag: '통신', re: /통신|방송|전파|정보보호|네트워크|선로설비|구내통신설비|통신공동구/ },
  { tag: '통계', re: /통계작성|통계간행물/ },
  { tag: '특정사업', re: /[가-힣0-9]+사업\s*(추진|지원)/ },
];

/** 국토교통부·국토교통위원회는 부동산뿐 아니라 도로·철도·항공·자동차·물류(교통)도
 *  소관이다(2026-08-14 발견 — "자동차손해배상 보장법 시행령"이 부동산으로 잘못
 *  붙었다는 오너 지적). 제목에 교통 키워드가 있고 부동산 키워드는 없으면 부동산
 *  대신 교통으로 바꾼다 — 둘 다 있으면(예: "도로변 주택정비") 부동산이 우선한다. */
const TRANSPORT_RE = /도로|철도|공항|항공|자동차|교통|물류|운수/;
const REAL_ESTATE_RE = /주택|부동산|정비법/;

function resolveLandVsTransport(tags, title) {
  if (tags.has('부동산') && TRANSPORT_RE.test(title) && !REAL_ESTATE_RE.test(title)) {
    tags.delete('부동산');
    tags.add('교통');
  }
  return tags;
}

/** 법제처 법령·행정규칙의 소관부처명 → 도메인 태그. COMMITTEE_TAGS와 같은
 *  원칙(2026-08-14, 오너 지시 — "대통령령이 부동산 관련이면 거기 게시글로
 *  추가해야지, 대통령령이라는 카테고리를 만들란 게 아니다") — 법령 자체가
 *  아니라 그 **내용이 속한 분야**로 분류한다. 부처 소관 사무가 실제로 그
 *  분야인 것만 넣는다, 애매한 부처는 뺀다(국방부 등은 대응하는 국회
 *  위원회 태그가 없는 것과 같은 이유로 뺐다).
 */
export const MINISTRY_TAGS = {
  국토교통부: ['부동산'],
  과학기술정보통신부: ['통신'],
  방송미디어통신위원회: ['통신'],
  국립전파연구원: ['통신'],
  기획재정부: ['세금'],
  재정경제부: ['세금'], // 기획재정부의 옛 이름(2008년 조직개편 전) — 법령 연혁엔 옛 이름 그대로 남아 있다
  재정경제원: ['세금'], // 재정경제부의 옛 이름(1998년 이전)
  국세청: ['세금'],
  관세청: ['세금'],
  환경부: ['환경'],
  농림축산식품부: ['농업'],
  해양수산부: ['농업'],
  문화체육관광부: ['문화'],
  보건복지부: ['보건'],
  산업통상자원부: ['산업'],
  중소벤처기업부: ['산업'],
  외교부: ['외교'],
  금융위원회: ['금융'],
  행정안전부: ['행정'],
  국가데이터처: ['통계'], // 2026-08-14 — 통계작성 승인고시가 여기서 나온다
};

function keywordTags(title) {
  const tags = new Set();
  for (const { tag, re } of KEYWORD_TAGS) {
    if (re.test(title)) tags.add(tag);
  }
  return tags;
}

/** 의안 하나(committee·title)에서 확실한 도메인 태그만 뽑는다. 순수 함수. */
export function tagBill(bill) {
  const tags = new Set([...(COMMITTEE_TAGS[bill.committee] || []), ...keywordTags(bill.title)]);
  return [...resolveLandVsTransport(tags, bill.title)];
}

/** 법령·행정규칙 하나(org·title)에서 확실한 도메인 태그만 뽑는다. 순수 함수.
 *  org는 법제처 응답의 소관부처명 그대로("국방부,방위사업청"처럼 콤마로
 *  여러 부처가 올 수 있다). */
export function tagDecree({ org, title }) {
  const tags = new Set(keywordTags(title));
  for (const ministry of (org || '').split(',').map((s) => s.trim())) {
    for (const t of MINISTRY_TAGS[ministry] || []) tags.add(t);
  }
  return [...resolveLandVsTransport(tags, title)];
}
